const fs=require('node:fs');
const {chromium}=require('C:/Users/mouzh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.REVIEW_URL||'http://127.0.0.1:50833/');
 await page.waitForFunction(()=>document.querySelector('#summary').textContent.includes('532'));
 const all=await page.locator('#rows tr,#conflictRows tr').count();
 if(all!==532)throw Error('pending rows '+all);
 if(await page.locator('#rows input:checked,#conflictRows input:checked').count())throw Error('preselected decisions');
 if(await page.locator('#rows select').evaluateAll(items=>items.some(x=>x.value!=='')))throw Error('preselected status');
 if(await page.locator('#rows textarea').evaluateAll(items=>items.some(x=>x.readOnly)))throw Error('pending manual value is locked');
 await page.selectOption('#group','来源冲突');
 if(await page.locator('#conflictRows tr').count()!==1||await page.locator('#rows tr').count()!==0)throw Error('conflict grouping');
 await page.click('#selectVisible');
 if(await page.locator('#conflictRows input:checked').count())throw Error('batch selection touched conflict');
 if(await page.locator('#businessItems > details').count()!==11)throw Error('business checklist missing');
 if(await page.locator('#businessItems select').evaluateAll(items=>items.some(x=>x.value!=='')))throw Error('business preselected');
 await page.screenshot({path:'tmp/goods-review-conflict-page.png',fullPage:false});
 if(await page.locator('#approvedQuote option').count()!==51)throw Error('quote source missing');
 await page.selectOption('#approvedQuote','0');
 if(!(await page.locator('#quoteEvidence').textContent()).includes('张朝文'))throw Error('approval provenance missing');
 await page.click('#saveOffers');
 if(!(await page.locator('#message').textContent()).includes('确认人'))throw Error('missing identity allowed');
 const [download]=await Promise.all([page.waitForEvent('download'),page.click('#exportReview')]);
 await download.saveAs('tmp/goods-exported-pending-review.json');
 const report=JSON.parse(fs.readFileSync('tmp/goods-exported-pending-review.json','utf8'));
 if(report.catalog.pending_count!==532||report.catalog.automatic_count!==237||!report.draft_can_continue)throw Error('workflow state');
 if(errors.length)throw Error(errors.join(';'));
 console.log(JSON.stringify({pending_rows:all,automatic_rows:report.catalog.automatic_count,approved_quotes:50,conflict_rows:1,no_preselected_conclusions:true,export:true,no_business_submission:true,page_errors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
