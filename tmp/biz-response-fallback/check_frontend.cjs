const fs = require('node:fs')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const req = createRequire('E:/code/python/weitaiAgentui/package.json')
const ts = req('typescript')
const source = fs.readFileSync('E:/code/python/weitaiAgentui/src/lib/api.ts', 'utf8')
const body = source.slice(source.indexOf('function friendlyMessage('), source.indexOf('function envelopeMessage('))
const script = ts.transpileModule(body, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText
const context = vm.createContext({})
vm.runInContext(script, context)
const degraded = context.friendlyMessage(422, '商务响应缺少条款或章节')
assert.ok(degraded.includes('关闭「起草商务响应」后重新生成'))
assert.ok(degraded.includes('【待补充】'))
assert.equal(context.friendlyMessage(422, '项目名称不能为空'), '项目名称不能为空')
assert.equal(context.friendlyMessage(500), '服务暂时不可用，请稍后重试')
console.log('Business-response fallback hint verified; unrelated 422 and service errors preserved.')
