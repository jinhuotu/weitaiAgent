"""Generic fallback pledges for an otherwise blank commitment subsection."""
from __future__ import annotations

from typing import Iterable


def generate_other_commitments(brief, existing_titles: Iterable[str] = ()) -> list[str]:
    existing = " ".join(existing_titles)
    topics = {"廉政", "贿赂", "扬尘", "信誉", "履约", "在建", "招标活动"}
    candidates = [
        ("现场", "我方承诺按照招标文件载明的项目条件组织实施，遵守合同约定和招标人现场管理要求，服从合理的工作协调安排，并对每项现场指令做好记录、复核和闭环处理，确保履约过程衔接顺畅、责任清晰、资料完整。"),
        ("分包", "我方承诺不转包、不违法分包，所有承接事项均按合同边界组织实施；我方将对工作接口、成果交付和责任分界进行持续核对，发现偏差及时纠正并保留过程记录，保证合同义务完整履行。"),
        ("审计", "我方承诺配合审计、监督检查和资料核验，按要求提供真实、完整、可追溯的记录；我方将对询问事项及时回应，对发现的问题主动整改并反馈结果，保证监督检查能够形成闭环。"),
        ("归档", "我方承诺在阶段完成和项目收口时整理竣工资料，按要求完成移交、归档和问题销项；我方将保持文件版本一致、签批手续完整、交接边界清楚，确保后续查验和运维使用顺利。"),
        ("应急", "我方承诺对重大事项及时报告，并依照既定应急程序组织响应、处置和复盘；我方将保持沟通渠道畅通，先控制影响范围，再核实原因、完善措施并向相关方反馈处理结果。"),
        ("保密", "我方承诺对履约过程中接触的资料承担保密义务，尊重并保护相关知识产权；我方将按授权范围使用文件和成果，未经许可不擅自复制、传播或改变用途，确保资料流转可控。"),
        ("工资", "我方承诺依法保障工资支付，按合同约定落实劳动用工管理和相关权益保障；我方将保持支付记录、沟通记录和问题处理记录完整，及时协调解决合理诉求，维护现场稳定。"),
        ("服务", "我方承诺在质量责任期内外持续配合服务，对提出的事项及时响应并跟踪闭环；我方将根据问题性质安排核查、处理、复验和反馈，保持服务过程连续，确保承诺事项得到落实。"),
        ("效力", "我方承诺本承诺书作为投标文件组成部分，与我方其他承诺具有同等约束效力；我方将按照承诺内容组织履约、接受监督并承担相应责任，任何变更均按合同和招标文件程序办理。"),
    ]
    blocked = {topic for topic in topics if topic in existing}
    return [text for topic, text in candidates if topic not in blocked]
